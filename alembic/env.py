"""Alembic environment: runs migrations against `CAPPER_DATABASE_URL` with the sync SQLite driver.

Migrations are written by hand, so no metadata is autogenerated here.
"""

from alembic import context
from sqlalchemy import create_engine, pool
from sqlalchemy.engine import make_url

from capper.config import StorageSettings


def _sync_url() -> str:
    url = make_url(StorageSettings().database_url)
    if url.drivername == "sqlite+aiosqlite":
        url = url.set(drivername="sqlite")
    return url.render_as_string(hide_password=False)


engine = create_engine(_sync_url(), poolclass=pool.NullPool)
with engine.connect() as connection:
    context.configure(connection=connection)
    with context.begin_transaction():
        context.run_migrations()
